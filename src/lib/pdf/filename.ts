/** Build a safe, deterministic download name from the assignment title. */
export function safePdfFileName(title: string): string {
  const slug = title
    .normalize("NFKD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 60)
    .replace(/-+$/g, "");
  return slug ? `${slug}-handwritten.pdf` : "assignment-handwritten.pdf";
}
